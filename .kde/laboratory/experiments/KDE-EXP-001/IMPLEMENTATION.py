#!/usr/bin/env python3
"""
LAB-ECU-001: Runtime ECU Self-Assessment
"""

import sys
import json
from datetime import datetime
from typing import Dict, List, Any

sys.path.insert(0, '/workspace/project/dnp3/.kde')

from runtime.ecu import RuntimeECU
from runtime.ecu.bootstrap import ECUBootstrap
from runtime.ecu.models import (
    ExecutionRequest, CapabilityType
)


class LaboratoryReport:
    def __init__(self):
        self.execution_trace = []
        self.ecu_decisions = []
        self.engine_participation = []
        self.seed_participation = []
        self.assessments = {}
        self.start_time = datetime.now()
    
    def log(self, component: str, message: str, data: Any = None):
        entry = {"timestamp": datetime.now().isoformat(), "component": component, "message": message, "data": data}
        self.execution_trace.append(entry)
        print(f"[{component}] {message}")
        if data:
            print(f"  Data: {str(data)[:200]}")
    
    def log_ecu_decision(self, decision_type: str, decision: str, rationale: str):
        entry = {"timestamp": datetime.now().isoformat(), "decision_type": decision_type, "decision": decision, "rationale": rationale}
        self.ecu_decisions.append(entry)
        print(f"  ECU: {decision_type} -> {decision}")
    
    def log_engine_participation(self, engine_id: str, role: str, details: Dict):
        entry = {"engine_id": engine_id, "role": role, "details": details, "timestamp": datetime.now().isoformat()}
        self.engine_participation.append(entry)
        print(f"  Engine: {engine_id} ({role})")
    
    def log_seed_participation(self, seed_id: str, role: str, details: Dict):
        entry = {"seed_id": seed_id, "role": role, "details": details, "timestamp": datetime.now().isoformat()}
        self.seed_participation.append(entry)
        print(f"  Seed: {seed_id} ({role})")
    
    def generate_report(self) -> str:
        elapsed = (datetime.now() - self.start_time).total_seconds()
        report = []
        report.append("# LAB-ECU-001: KDE Runtime ECU Self-Assessment")
        report.append("")
        report.append(f"**Report Date**: {datetime.now().isoformat()}")
        report.append(f"**Execution Duration**: {elapsed:.2f} seconds")
        report.append("")
        report.append("## Execution Flow")
        report.append("Bootstrap -> Runtime ECU -> Engine Discovery -> Seed Discovery -> Capability Resolution -> Execution Planning -> Selected Engines -> Result Aggregation")
        report.append("")
        report.append("## ECU Decision Log")
        for d in self.ecu_decisions:
            report.append(f"- [{d['timestamp']}] {d['decision_type']}: {d['decision']} (Rationale: {d['rationale']})")
        report.append("")
        report.append("## Engine Participation")
        for e in self.engine_participation:
            report.append(f"- {e['engine_id']} ({e['role']}): {json.dumps(e['details'])}")
        report.append("")
        report.append("## Seed Participation")
        if self.seed_participation:
            for s in self.seed_participation:
                report.append(f"- {s['seed_id']} ({s['role']}): {json.dumps(s['details'])}")
        else:
            report.append("No seeds selected")
        report.append("")
        report.append("## Runtime Assessments")
        for comp, assess in self.assessments.items():
            report.append(f"### {comp}: {assess['score']}/10")
            for ev in assess['evidence']:
                report.append(f"- {ev}")
            if assess.get('issues'):
                report.append("Issues:")
                for iss in assess['issues']:
                    report.append(f"  - {iss}")
        report.append("")
        report.append("## Runtime Health")
        for check, status in self._assess_runtime_health().items():
            report.append(f"- {check}: {status['status']} - {status.get('details', '')}")
        report.append("")
        report.append("## Runtime Readiness Score")
        scores = [(k, v['score']) for k, v in self.assessments.items()]
        overall = sum(s for _, s in scores) / len(scores) if scores else 0
        report.append(f"**Overall Score**: {overall:.1f}/10")
        report.append("")
        for comp, score in scores:
            report.append(f"| {comp} | {score}/10 |")
        report.append("")
        report.append("## Recommendations")
        for rec in self._generate_recommendations():
            report.append(f"- [{rec['priority']}] {rec['component']}: {rec['recommendation']} (Evidence: {rec['evidence']})")
        report.append("")
        report.append(f"**Total Events**: {len(self.execution_trace)}")
        report.append("")
        report.append("---")
        report.append("*LAB-ECU-001 Generated by KDE Runtime Self-Assessment*")
        return '\n'.join(report)
    
    def _assess_runtime_health(self) -> Dict:
        return {
            'Engine Discovery': {'status': 'OK' if self.engine_participation else 'FAIL', 'details': f"{len(set(e['engine_id'] for e in self.engine_participation))} engines"},
            'Seed Discovery': {'status': 'OK', 'details': f"{len(set(s['seed_id'] for s in self.seed_participation))} seeds"},
            'Capability Resolution': {'status': 'OK' if self.ecu_decisions else 'FAIL', 'details': f"{len([d for d in self.ecu_decisions if d['decision_type'] == 'capability_resolution'])} resolutions"},
        }
    
    def _generate_recommendations(self) -> List[Dict]:
        recs = []
        for comp, assess in self.assessments.items():
            if comp == 'Overall Runtime Readiness':
                continue
            if assess['score'] < 7:
                for iss in assess.get('issues', []):
                    recs.append({'priority': 'High' if assess['score'] < 5 else 'Medium', 'component': comp, 'recommendation': f"Address: {iss}", 'evidence': f"Score: {assess['score']}/10"})
        return recs


def run_laboratory():
    print("=" * 60)
    print("LAB-ECU-001: KDE Runtime ECU Self-Assessment")
    print("=" * 60)
    print()
    
    report = LaboratoryReport()
    
    # Bootstrap
    report.log("BOOTSTRAP", "Initializing Bootstrap")
    try:
        bootstrap = ECUBootstrap('/workspace/project/dnp3/.kde')
        init_result = bootstrap.bootstrap()
        
        report.log("BOOTSTRAP", f"Initialization: {'Success' if init_result.success else 'Failed'}", {
            "engines": init_result.engines_registered, "seeds": init_result.seeds_registered
        })
        
        report.assessments['Bootstrap'] = {
            'score': 10 if init_result.success else 0,
            'evidence': [f"Success: {init_result.success}", f"Engines: {init_result.engines_registered}", f"Seeds: {init_result.seeds_registered}"],
            'issues': init_result.warnings if init_result.warnings else []
        }
        
        report.log_ecu_decision("bootstrap", f"Registered {init_result.engines_registered} engines, {init_result.seeds_registered} seeds", "Bootstrap completed")
        
    except Exception as e:
        report.log("BOOTSTRAP", f"Failed: {e}", None)
        report.assessments['Bootstrap'] = {'score': 0, 'evidence': [str(e)], 'issues': ["Bootstrap failed"]}
        print(report.generate_report())
        return
    
    ecu = bootstrap.ecu
    validation = bootstrap.get_validation_report()
    
    # Runtime ECU
    runtime_state = ecu.get_runtime_state()
    report.assessments['Runtime ECU'] = {
        'score': 10 if runtime_state.get('initialized') else 0,
        'evidence': [f"Initialized: {runtime_state.get('initialized')}", f"Requests: {runtime_state.get('total_requests_processed')}"],
        'issues': []
    }
    
    # Engine Registry
    engine_reg = ecu.engine_registry.get_registry_summary()
    all_engines = ecu.engine_registry.get_all_engines()
    
    report.log("ENGINE_REGISTRY", f"Found {engine_reg['total_engines']} engines")
    
    for engine in all_engines:
        report.log_engine_participation(engine.engine_id, engine.status.value, {
            "version": engine.version, "capabilities": len(engine.capabilities), "priority": engine.priority
        })
        report.log_ecu_decision("engine_assessment", f"{engine.engine_id} assessed", f"Status: {engine.status.value}")
    
    reg_score = 10 if engine_reg['total_engines'] > 0 else 0
    report.assessments['Engine Registry'] = {
        'score': reg_score,
        'evidence': [f"Total: {engine_reg['total_engines']}", f"Active: {engine_reg.get('active', 0)}", f"Discovery complete: {engine_reg.get('discovery_complete')}"],
        'issues': [] if engine_reg['total_engines'] > 0 else ["No engines discovered"]
    }
    
    # Seed Registry
    seed_reg = ecu.seed_registry.get_registry_summary()
    all_seeds = ecu.seed_registry.get_all_seeds()
    
    report.log("SEED_REGISTRY", f"Found {seed_reg['total_seeds']} seeds")
    
    for seed in all_seeds:
        report.log_seed_participation(seed.seed_id, seed.status.value, {
            "version": seed.version, "capabilities": [c.name for c in seed.capabilities]
        })
    
    report.assessments['Seed Registry'] = {
        'score': 10 if seed_reg['total_seeds'] > 0 else 5,
        'evidence': [f"Total: {seed_reg['total_seeds']}", f"Frozen: {seed_reg.get('frozen', 0)}"],
        'issues': []
    }
    
    # Capability Resolution
    test_request = ExecutionRequest(
        request_id='LAB-ECU-001-TEST',
        description='Runtime self-assessment test',
        required_capabilities=[CapabilityType.REASONING, CapabilityType.ANALYSIS],
        keywords=['self-assessment', 'runtime']
    )
    
    resolution = ecu.resolve_capabilities(test_request)
    
    report.log("ECU", f"Matched {resolution['engine_count']} engines")
    report.log_ecu_decision("capability_resolution", f"{resolution['engine_count']} engines matched", f"Top: {resolution.get('top_engine')} (conf: {resolution.get('top_engine_confidence', 0):.2f})")
    
    cap_score = min(resolution['engine_count'] * 2.5, 10) if resolution['engine_count'] > 0 else 0
    report.assessments['Capability Resolution'] = {
        'score': cap_score,
        'evidence': [f"Matched: {resolution['engine_count']}", f"Confidence: {resolution.get('top_engine_confidence', 0):.2f}"],
        'issues': [] if resolution['engine_count'] > 0 else ["No engines matched"]
    }
    
    # Execution Planning
    plan_result = ecu.create_execution_plan(test_request)
    plan_summary = plan_result.plan_summary or {}
    
    if plan_result.success:
        report.log("ECU", f"Plan created: {plan_result.plan_id}", {"mode": plan_summary.get('mode'), "steps": plan_summary.get('step_count')})
        report.log_ecu_decision("execution_planning", f"Plan {plan_result.plan_id}", f"Mode: {plan_summary.get('mode')}")
    else:
        report.log("ECU", f"Plan failed: {plan_result.error_message}", None)
    
    report.assessments['Execution Planning'] = {
        'score': 10 if plan_result.success else 5,
        'evidence': [f"Success: {plan_result.success}", f"Mode: {plan_summary.get('mode', 'N/A')}"],
        'issues': [f"Failed: {plan_result.error_message}"] if not plan_result.success else []
    }
    
    # Policy
    policy_summary = ecu.policy_layer.get_policy_summary()
    report.assessments['Policy Enforcement'] = {
        'score': 10 if policy_summary.get('total_violations', 0) == 0 else 5,
        'evidence': [f"Rules: {policy_summary.get('total_rules', 0)}", f"Violations: {policy_summary.get('total_violations', 0)}"],
        'issues': []
    }
    report.log_ecu_decision("policy", "Policy active", f"{policy_summary.get('total_rules', 0)} rules loaded")
    
    # Integration
    int_score = 10
    int_issues = []
    if validation and not validation.get('ready_for_execution'):
        int_score -= 3
        int_issues.append("Runtime not ready")
    
    report.assessments['Runtime Integration'] = {
        'score': max(int_score, 0),
        'evidence': [f"Validation: {validation.get('status') if validation else 'N/A'}", f"Ready: {validation.get('ready_for_execution') if validation else False}"],
        'issues': int_issues
    }
    
    # Overall
    all_scores = [a['score'] for a in report.assessments.values()]
    overall = sum(all_scores) / len(all_scores) if all_scores else 0
    report.assessments['Overall Runtime Readiness'] = {
        'score': overall,
        'evidence': [f"Based on {len(all_scores)} components"],
        'issues': []
    }
    
    # Generate report
    print()
    print("Generating report...")
    full_report = report.generate_report()
    
    report_path = '/workspace/project/dnp3/.kde/laboratory/LAB-ECU-001-REPORT.md'
    with open(report_path, 'w') as f:
        f.write(full_report)
    
    print(f"Report saved: {report_path}")
    print()
    print("=" * 60)
    print("LAB-ECU-001 COMPLETE")
    print("=" * 60)
    
    return full_report


if __name__ == "__main__":
    run_laboratory()
