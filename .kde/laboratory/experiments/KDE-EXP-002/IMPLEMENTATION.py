def assess_operational_status(report: LABECU003Report) -> Dict:
    """Assess whether Runtime ECU functions as operational authority"""
    
    status = {
        'title': 'Runtime ECU Operational Assessment',
        'evidence': [],
        'conclusion': 'UNKNOWN'
    }
    
    passed_count = sum(1 for r in report.scenario_results.values() if r['passed'])
    total = len(report.scenario_results)
    
    # Check key indicators
    indicators = {
        'Runtime Orchestrator': False,
        'Capability Resolver': False,
        'Execution Planner': False,
        'Runtime Authority': False
    }
    
    # Scenario 1: Initialization
    if report.scenario_results.get('1', {}).get('passed'):
        indicators['Runtime Orchestrator'] = True
        status['evidence'].append("Runtime ECU successfully initializes runtime components")
    
    # Scenario 2: Discovery
    if report.scenario_results.get('2', {}).get('passed'):
        indicators['Runtime Orchestrator'] = True
        status['evidence'].append("Runtime ECU discovers all runtime assets")
    
    # Scenario 3: Capability Resolution
    s3 = report.scenario_results.get('3', {})
    if s3.get('passed') and s3.get('evidence'):
        if any('engines matched' in e for e in s3['evidence']):
            indicators['Capability Resolver'] = True
            status['evidence'].append("Runtime ECU resolves capabilities to engines")
    
    # Scenario 4: Execution Planning
    s4 = report.scenario_results.get('4', {})
    if s4.get('passed') and s4.get('evidence'):
        if any('Plan' in e for e in s4['evidence']):
            indicators['Execution Planner'] = True
            status['evidence'].append("Runtime ECU creates execution plans")
    
    # Scenario 5: Policy Enforcement
    if report.scenario_results.get('5', {}).get('passed'):
        indicators['Runtime Authority'] = True
        status['evidence'].append("Runtime ECU enforces runtime policy")
    
    # Scenario 6: Failure Handling
    if report.scenario_results.get('6', {}).get('passed'):
        status['evidence'].append("Runtime ECU handles failures gracefully")
    
    # Scenario 7: End-to-End
    if report.scenario_results.get('7', {}).get('passed'):
        indicators['Runtime Orchestrator'] = True
        indicators['Capability Resolver'] = True
        indicators['Execution Planner'] = True
        status['evidence'].append("Runtime ECU orchestrates complete end-to-end execution")
    
    # Determine conclusion
    indicators_list = [k for k, v in indicators.items() if v]
    
    if len(indicators_list) >= 4:
        status['conclusion'] = "FULLY OPERATIONAL"
    elif len(indicators_list) >= 2:
        status['conclusion'] = "PARTIALLY OPERATIONAL"
    else:
        status['conclusion'] = "REQUIRES ENGINEERING"
    
    status['evidence'].insert(0, f"\nScenarios Passed: {passed_count}/{total}")
    status['evidence'].insert(1, f"\nOperational Indicators Demonstrated: {len(indicators_list)}/4")
    
    for ind, val in indicators.items():
        status['evidence'].append(f"  - {ind}: {'YES' if val else 'NO'}")
    
    status['evidence'].append(f"\nConclusion: {status['conclusion']}")
    
    return status


