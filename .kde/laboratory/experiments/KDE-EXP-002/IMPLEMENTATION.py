class LABECU003Report:
    def __init__(self):
        self.traces = []
        self.scenario_results = {}
        self.start_time = datetime.now()
        
    def log(self, component: str, message: str, data: Any = None):
        entry = {
            "timestamp": datetime.now().isoformat(),
            "component": component,
            "message": message,
            "data": data
        }
        self.traces.append(entry)
        print(f"[{component}] {message}")
        if data and isinstance(data, dict):
            for k, v in data.items():
                print(f"    {k}: {v}")
    
    def save_report(self, path: str):
        report = self.generate_report()
        with open(path, 'w') as f:
            f.write(report)
        print(f"\nReport saved: {path}")
        return report
    
    def generate_report(self) -> str:
        elapsed = (datetime.now() - self.start_time).total_seconds()
        lines = []
        lines.append("# LAB-ECU-003: Runtime ECU Operational Test Drive")
        lines.append("")
        lines.append(f"**Report Date**: {datetime.now().isoformat()}")
        lines.append(f"**Execution Duration**: {elapsed:.2f} seconds")
        lines.append("")
        
        for scenario, result in self.scenario_results.items():
            lines.append(f"\n## Scenario {scenario}: {result['title']}")
            lines.append(f"**Status**: {'PASS' if result['passed'] else 'FAIL'}")
            lines.append(f"\n### Evidence")
            for evidence in result['evidence']:
                lines.append(f"- {evidence}")
            if result.get('issues'):
                lines.append(f"\n### Issues")
                for issue in result['issues']:
                    lines.append(f"- {issue}")
            if result.get('trace'):
                lines.append(f"\n### Execution Trace")
                for t in result['trace']:
                    lines.append(f"- [{t['timestamp']}] {t['component']}: {t['message']}")
        
        lines.append(f"\n## Summary")
        passed = sum(1 for r in self.scenario_results.values() if r['passed'])
        total = len(self.scenario_results)
        lines.append(f"**Scenarios Passed**: {passed}/{total}")
        lines.append("")
        lines.append("---")
        lines.append("*LAB-ECU-003 Generated by KDE Runtime Operational Test Drive*")
        return '\n'.join(lines)


