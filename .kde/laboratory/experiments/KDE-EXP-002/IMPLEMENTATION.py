def run_scenario_5_policy_enforcement(ecu: RuntimeECU) -> Dict:
    """Test Scenario 5: Runtime Policy"""
    result = {
        'title': 'Runtime Policy',
        'passed': True,
        'evidence': [],
        'issues': [],
        'trace': []
    }
    
    policy = ecu.policy_layer
    
    # Test unknown engine
    from runtime.ecu.models import EngineMetadata, EngineStatus, EngineStability
    
    unknown_engine = EngineMetadata(
        engine_id='UNKNOWN-ENGINE',
        directory='unknown',
        name='Unknown Engine',
        codename='unknown',
        version='1.0.0',
        status=EngineStatus.ACTIVE,
        stability=EngineStability.STABLE
    )
    
    validation = policy.validate_engine(unknown_engine)
    
    result['trace'].append({
        'timestamp': datetime.now().isoformat(),
        'component': 'Policy',
        'message': f"Unknown engine validation: violated={validation.violated}"
    })
    
    result['evidence'].append(f"Unknown engine test: {'BLOCKED' if validation.violated else 'ALLOWED'}")
    
    if not validation.violated:
        result['issues'].append("Unknown engine was not blocked by policy")
        result['passed'] = False
    
    # Test placeholder engine
    placeholder_engine = EngineMetadata(
        engine_id='PLACEHOLDER-001',
        directory='placeholder',
        name='Placeholder',
        codename='placeholder',
        version='0.0.0',
        status=EngineStatus.ACTIVE,
        stability=EngineStability.UNSTABLE
    )
    
    placeholder_validation = policy.validate_engine(placeholder_engine)
    result['evidence'].append(f"Placeholder engine test: {'BLOCKED' if placeholder_validation.violated else 'ALLOWED'}")
    
    # Test valid engine
    all_engines = ecu.engine_registry.get_all_engines()
    if all_engines:
        valid_engine = all_engines[0]
        valid_validation = policy.validate_engine(valid_engine)
        result['evidence'].append(f"Valid engine ({valid_engine.engine_id}): {'PASSED' if not valid_validation.violated else 'VIOLATION'}")
    
    result['evidence'].append(f"\nPolicy rules active: {policy.get_policy_summary()['total_rules']}")
    
    return result


